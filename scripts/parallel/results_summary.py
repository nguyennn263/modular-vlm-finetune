#!/usr/bin/env python3
"""One file with every full-image re-score collected so far, next to the old
(first-tile crop) number of the same checkpoint where one exists.

    python scripts/parallel/results_summary.py   -> plans/results-full-image.md
"""
from __future__ import annotations
import json, re, time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OLD = Path("/Users/tcx/Documents/personal/Repo/modular-vlm-finetune")   # main checkout: old eval JSONs
OUT = ROOT / "plans" / "results-full-image.md"
METRICS = ["accuracy", "precision", "recall", "f1", "bleu", "rouge_l", "meteor", "cider"]
BRIDGE = {"mt": "multi_token", "res": "residual", "ta": "tile_attention", "mq": "mini_qformer", "qf": "qformer"}
RQ5 = {"feat": "expA-align-feat", "logit01": "expA-align-logit-a01", "logit1": "expA-align-logit", "random": "expA-random"}


def _old(tag: str, split: str) -> Path | None:
    """The first-tile-crop eval JSON of the same checkpoint, if we have it."""
    tag = re.sub(r"-r2$", "", tag)
    if m := re.fullmatch(r"(mt|res|ta|mq|qf)-s(\d+)(?:-t1-full)?", tag):
        b, s = BRIDGE[m[1]], m[2]
        if split == "test":
            return OLD / f"outputs/test_eval/test-eval_{b}_s{s}/eval_test.json"
        return OLD / f"checkpoints/expA/seed{s}/{b}/eval_val.json"
    if m := re.fullmatch(r"l([13])ep-s(\d+)(?:-t1-(?:full|crop))?", tag):
        return OLD / f"checkpoints/expA-lora16{'-3ep' if m[1] == '3' else ''}/seed{m[2]}/multi_token/eval_{split}.json"
    if m := re.fullmatch(r"l1ep-(res|ta|mq|qf)-s(\d+)", tag):
        return OLD / f"checkpoints/expA-lora16/seed{m[2]}/{BRIDGE[m[1]]}/eval_{split}.json"
    if m := re.fullmatch(r"rq5-(\w+)-s(\d+)", tag):
        return OLD / f"checkpoints/{RQ5[m[1]]}/seed{m[2]}/multi_token/eval_{split}.json"
    return None


def _rows() -> list[dict]:
    rows = []
    for f in sorted((ROOT / "outputs").glob("*/*/**/eval_*.json")):
        kind = f.relative_to(ROOT / "outputs").parts[0]
        if kind not in ("input_diag", "regen_full"):
            continue
        d = json.loads(f.read_text())
        tag = f.relative_to(ROOT / "outputs").parts[1]
        split = f.stem.split("_", 1)[1]
        old = _old(tag, split)
        old_f1 = json.loads(old.read_text())["f1"] * 100 if old and old.exists() else None
        rows.append({"tag": tag, "split": split, "n": d.get("n"), "loss": d.get("loss"),
                     "gen_image": d.get("gen_image", "full"), "pooled": d.get("pooled_input", "default"),
                     "n_tiles": d.get("n_tiles", 1), **{k: d.get(k, 0) * 100 for k in METRICS},
                     "old_f1": old_f1, "file": str(f.relative_to(ROOT))})
    return rows


def _table(rows: list[dict]) -> list[str]:
    out = ["| job | split | tiles | input | image | n | Acc | P | R | F1 | BLEU | ROUGE | METEOR | CIDEr | loss | F1 cũ (crop) | ΔF1 |",
           "|---|---|--:|---|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|"]
    for r in rows:
        old = f"{r['old_f1']:.2f}" if r["old_f1"] is not None else "—"
        delta = f"{r['f1'] - r['old_f1']:+.2f}" if r["old_f1"] is not None else "—"
        loss = f"{r['loss']:.3f}" if isinstance(r["loss"], (int, float)) else "—"
        leak = " ⚠️ LEAK" if re.match(r"(l1ep-)?qf-", r["tag"]) else ""
        out.append(f"| {r['tag']}{leak} | {r['split']} | {r['n_tiles']} | {r['pooled']} | {r['gen_image']} | {r['n']} | "
                   + " | ".join(f"{r[k]:.2f}" for k in METRICS) + f" | {loss} | {old} | {delta} |")
    return out


def main() -> None:
    rows = _rows()
    groups = [
        ("Tab. main / stability (Multi-Token plain + LoRA)", lambda t: re.match(r"(mt-s\d+|l[13]ep-s\d+)(-t1-(full|crop))?(-r2)?$", t)),
        ("RQ3 — tiles and pooled input", lambda t: re.search(r"-t[36]-|-t1-full-mean", t)),
        ("Tab. levers (RQ5)", lambda t: t.startswith("rq5-")),
        ("Tab. bridges", lambda t: re.match(r"(res|ta|mq|qf)-s|l1ep-(res|ta|mq|qf)-", t)),
    ]
    lines = ["# Re-score with the whole image (`--gen-image full`) — every result collected so far", "",
             f"*Auto-generated by `scripts/parallel/results_summary.py` at {time.strftime('%Y-%m-%d %H:%M')}. "
             "All metrics from `metrics.vqa_metrics.score_answers`, ×100. \"F1 cũ\" = same checkpoint scored "
             "the old way (generation fed the first 448px crop). Raw files under `outputs/`.*", "",
             "> ⚠️ **Full Q-Former (`qf-*`, `l1ep-qf-*`) — do not use.** Its training input included the "
             "reference answer, which the bridge cross-attends to without a mask (collator.py:136-139, "
             "trainer.py:606/620-622, bridge_modules.py:598); the checkpoints themselves are compromised, so "
             "re-scoring cannot fix them. Light Q-Former (`mq-*`) is not text-conditioned and is unaffected.", ""]
    seen = set()
    for title, pick in groups:
        sel = [r for r in rows if pick(r["tag"])]
        seen |= {id(r) for r in sel}
        lines += [f"## {title} ({len(sel)} results)", ""] + (_table(sel) if sel else ["*(none yet)*"]) + [""]
    ood = ROOT / "outputs" / "ood_full" / "table.json"
    if ood.exists():
        t = json.loads(ood.read_text())
        lines += ["## Tab. OOD (shared questions, mean ± std over 3 sampling seeds)", "",
                  "| dataset | F1 Vintern | F1 ours (full) | F1 ours (old crop) | CIDEr Vintern | CIDEr ours (full) |",
                  "|---|--:|--:|--:|--:|--:|"]
        for ds, v in t.items():
            m = v["mean_std"]
            g = lambda k: f"{m[k][0]:.2f} ± {m[k][1]:.2f}"
            lines.append(f"| {ds} | {g('vintern.f1')} | {g('ours_full.f1')} | {g('ours_crop.f1')} | "
                         f"{g('vintern.cider')} | {g('ours_full.cider')} |")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"[summary] {len(rows)} results -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
